// Regenerates src/lib/scorer/wordlist-data.ts.
// Run: npm run update-wordlist — then commit the result.
//
// Source: google-10000-english (frequency-ranked most common English words,
// derived from the Google Trillion Word Corpus). Rank order matters: the
// segmenter prefers common words when splits are ambiguous.
//
// The same list also feeds a letter-bigram model (with ^ start / $ end
// markers) used for the pronounceability score, so both features share one
// data file and one notion of "English-like".

import { writeFileSync } from "node:fs";

const SOURCE =
  "https://raw.githubusercontent.com/first20hours/google-10000-english/master/google-10000-english-usa-no-swears.txt";

const res = await fetch(SOURCE);
if (!res.ok) {
  throw new Error(`fetch failed: HTTP ${res.status} from ${SOURCE}`);
}
const text = await res.text();

const seen = new Set();
const words = [];
for (const line of text.split("\n")) {
  const w = line.trim();
  if (!/^[a-z]{2,}$/.test(w) || seen.has(w)) continue;
  seen.add(w);
  words.push(w);
}
if (words.length < 5000) {
  throw new Error(`suspiciously few words (${words.length}) — refusing to write`);
}

// Bigram counts over ^word$ paths. Index layout: 0 = '^', 1–26 = 'a'–'z',
// 27 = '$'; table is 28×28 row-major, row = previous char, col = next char.
const N = 28;
const counts = new Array(N * N).fill(0);
const idx = (ch) => ch.charCodeAt(0) - 97 + 1;
for (const w of words) {
  let prev = 0;
  for (const ch of w) {
    counts[prev * N + idx(ch)]++;
    prev = idx(ch);
  }
  counts[prev * N + 27]++;
}

const logs = [];
for (let row = 0; row < N; row++) {
  let total = 0;
  for (let col = 0; col < N; col++) total += counts[row * N + col] + 0.5;
  for (let col = 0; col < N; col++) {
    logs.push(Math.round(Math.log2((counts[row * N + col] + 0.5) / total) * 100) / 100);
  }
}

const stamp = new Date().toISOString().slice(0, 10);
const out = `// Generated by scripts/update-wordlist.mjs on ${stamp} — do not edit.
// Source: ${SOURCE}
// ${words.length} words, frequency-ranked (index = rank).

export const WORDS: string[] = ${JSON.stringify(words)};

// Letter-bigram log2 probabilities over the wordlist, Laplace-smoothed.
// 28×28 row-major; index 0 = '^' (word start), 1–26 = 'a'–'z', 27 = '$' (end).
export const BIGRAM_LOG2: number[] = ${JSON.stringify(logs)};
`;

writeFileSync("src/lib/scorer/wordlist-data.ts", out);
console.log(`wordlist-data.ts written: ${words.length} words + ${logs.length}-entry bigram table`);
