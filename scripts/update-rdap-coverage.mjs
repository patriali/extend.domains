// Regenerates src/lib/rdap-coverage-data.ts from the RDAP.org deployment
// dashboard (an HTML table; there is no JSON export as of 2026-07).
// Run: npm run update-rdap-coverage — then commit the result.
//
// Only TLDs marked as having NO RDAP service are stored: at runtime a TLD
// missing from the (live, cached) IANA bootstrap consults this set to decide
// between "no RDAP for this TLD" (render immediately, don't spin) and "try
// the rdap.org fallback" (dashboard says a server exists, or TLD unknown).

import { writeFileSync } from "node:fs";
import { domainToASCII } from "node:url";

const SOURCE = "https://deployment.rdap.org/";

const res = await fetch(SOURCE);
if (!res.ok) {
  throw new Error(`fetch failed: HTTP ${res.status} from ${SOURCE}`);
}
const html = await res.text();

const rows = html.match(/<tr[^>]*>.*?<\/tr>/gs) ?? [];
const noRdap = [];
let yes = 0;
for (const row of rows) {
  const cells = row.match(/<td[^>]*>.*?<\/td>/gs);
  if (cells === null || cells.length < 4) continue;
  const tldMatch = cells[0].match(/title="\.([^"]+)"/);
  if (tldMatch === null) continue;
  const rdapText = cells[3].replace(/<[^>]+>/g, "").trim(); // "Yes" | "No" | "No*" | "-"
  const ascii = domainToASCII(tldMatch[1]).toLowerCase();
  if (ascii === "") {
    throw new Error(`could not punycode TLD: ${tldMatch[1]}`);
  }
  if (/^yes$/i.test(rdapText)) yes++;
  else noRdap.push(ascii);
}

if (yes < 500 || noRdap.length < 20) {
  throw new Error(
    `suspicious parse (${yes} yes / ${noRdap.length} no) — dashboard layout changed?`,
  );
}
noRdap.sort();

const stamp = new Date().toISOString().slice(0, 10);
const out = `// Generated by scripts/update-rdap-coverage.mjs on ${stamp} — do not edit.
// Source: ${SOURCE} (deployment dashboard table; TLDs punycoded).
// ${yes} TLDs with RDAP, ${noRdap.length} without.

/** TLDs with no known RDAP service anywhere (registry or rdap.org). */
export const NO_RDAP_TLDS: string[] = ${JSON.stringify(noRdap)};

export const RDAP_COVERAGE_GENERATED = "${stamp}";
`;

writeFileSync("src/lib/rdap-coverage-data.ts", out);
console.log(`rdap-coverage-data.ts written: ${yes} with RDAP, ${noRdap.length} without`);
